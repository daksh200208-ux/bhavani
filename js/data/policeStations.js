/**
 * Helper to calculate haversine distance in kilometers
 */
function calculateDistanceKm(lat1, lon1, lat2, lon2) {
  const R = 6371; // Earth radius in km
  const dLat = (lat2 - lat1) * Math.PI / 180;
  const dLon = (lon2 - lon1) * Math.PI / 180;
  const a = 
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) * 
    Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return parseFloat((R * c).toFixed(2));
}

/**
 * Find the nearest police station from coordinates among all 49 Kanpur stations
 */
function findNearestThana(lat, lng) {
  let nearest = null;
  let minDistance = Infinity;

  for (const station of KANPUR_POLICE_STATIONS) {
    const dist = calculateDistanceKm(lat, lng, station.lat, station.lng);
    if (dist < minDistance) {
      minDistance = dist;
      nearest = {
        id: station.id,
        name: station.name,
        cug: station.cug,
        phone: station.phone,
        sho: station.sho,
        distKm: dist,
        distanceKm: dist,
        lat: station.lat,
        lng: station.lng,
        zone: station.zone,
        circle: station.circle,
        address: station.address
      };
    }
  }

  return nearest;
}

/**
 * Compute nearest thana, urban circuity-adjusted walking distance, and pedestrian ETA
 * Speed: 5.0 km/h (12 mins/km)
 * Detour factor: 1.30 (Urban street circuity)
 * ETA = ceil(directKm * 1.30 * 12) = ceil(directKm * 15.6)
 */
function computeNearestThanaAndEta(userLat, userLng) {
  let nearest = null;
  let minDistance = Infinity;

  for (const station of KANPUR_POLICE_STATIONS) {
    const dist = calculateDistanceKm(userLat, userLng, station.lat, station.lng);
    if (dist < minDistance) {
      minDistance = dist;
      nearest = station;
    }
  }

  const directDistKm = parseFloat(minDistance.toFixed(2));
  const streetDistKm = parseFloat((minDistance * 1.30).toFixed(2));
  // Walking speed 5.0 km/h = 12 mins/km; with 1.30 detour = 15.6 mins/km
  const etaMinutes = Math.max(1, Math.ceil(minDistance * 1.30 * 12));

  return {
    station: nearest,
    distanceKm: directDistKm,
    streetDistanceKm: streetDistKm,
    etaMinutes: etaMinutes,
    etaString: `${etaMinutes} min${etaMinutes > 1 ? 's' : ''}`,
    googleMapsUrl: nearest ? getGoogleMapsWalkingUrl(nearest.lat, nearest.lng) : ''
  };
}

/**
 * Universal cross-platform Google Maps Walking Navigation URL
 */
function getGoogleMapsWalkingUrl(destLat, destLng) {
  const lat = typeof destLat === 'number' ? destLat.toFixed(5) : parseFloat(destLat).toFixed(5);
  const lng = typeof destLng === 'number' ? destLng.toFixed(5) : parseFloat(destLng).toFixed(5);
  return `https://www.google.com/maps/dir/?api=1&destination=${lat},${lng}&travelmode=walking`;
}

